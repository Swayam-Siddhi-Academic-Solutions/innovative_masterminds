-- Regression checks on the installed curriculum. Roll back all synthetic transactions.
begin;
set local plpgsql.check_asserts=on;
do $check$
declare
  hash_a text := replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');
  hash_b text := replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');
  email_a text := 'self-learning-test-a@example.invalid'; email_b text := 'self-learning-test-b@example.invalid';
  a jsonb; b jsonb; ids text[]; p uuid; pb uuid; owner_id uuid; u text; k int; stamp text;
  tx text := 'QA'||upper(replace(gen_random_uuid()::text,'-','')); receipt text;
  catalog jsonb; lesson jsonb; test_count int;
begin
  select user_id into strict owner_id from public.im_paper_admins limit 1;
  select array_agg(id order by id) into ids from (select id from public.im_sl_chapters order by id limit 11) q;
  assert cardinality(ids)=11,'Eleven populated chapters required';
  assert not has_function_privilege('anon','public.im_sl_student(text,text,text,jsonb)','execute');
  assert not has_function_privilege('authenticated','public.im_sl_staff(uuid,text,jsonb)','execute');
  assert not has_table_privilege('anon','public.im_sl_units','select');
  assert not has_table_privilege('authenticated','public.im_sl_passes','update');
  assert (select count(*)=8 and bool_and(relrowsecurity) from pg_class where relnamespace='public'::regnamespace and relname like 'im_sl_%' and relkind='r');
  update public.im_sl_release set accepting=true where singleton;
  catalog:=public.im_sl_catalog();
  assert (catalog->>'accepting')::boolean;
  assert jsonb_array_length(catalog->'chapters')=(select count(*) from public.im_sl_chapters);
  assert not ((catalog->'chapters'->0) ?| array['body','question','answer','challenge']);
  a:=public.im_sl_student('register',hash_a,email_a,'{"name":"Learning QA A"}');
  p:=(a->>'id')::uuid;
  assert a->>'status'='awaiting_payment' and a->>'amount'='599';
  assert a->>'startsAt' is null and a->>'endsAt' is null;
  assert public.im_sl_student('register',hash_a,email_a,'{"name":"Learning QA A"}')->>'id'=p::text;
  begin perform public.im_sl_student('status',hash_a,email_b); assert false,'Wrong credential pair accepted';
    exception when raise_exception then assert sqlerrm like 'The email and learning key%'; end;
  b:=public.im_sl_student('register',hash_b,email_b,'{"name":"Learning QA B"}');pb:=(b->>'id')::uuid;
  begin perform public.im_sl_student('open',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));assert false,'Unpaid access';
    exception when raise_exception then assert sqlerrm like 'An active%'; end;
  a:=public.im_sl_student('payment',hash_a,email_a,jsonb_build_object('pass',p,'ref',tx,'payer','Synthetic A'));
  assert a->>'status'='in_review' and a->>'startsAt' is null;
  a:=public.im_sl_student('payment',hash_a,email_a,jsonb_build_object('pass',p,'ref',tx,'payer','Synthetic A'));
  assert a->>'status'='in_review';
  begin perform public.im_sl_student('payment',hash_b,email_b,jsonb_build_object('pass',pb,'ref',tx,'payer','Synthetic B'));assert false,'Duplicate payment';
    exception when raise_exception then assert sqlerrm like 'This reference is already%'; end;
  begin perform public.im_sl_staff(gen_random_uuid(),'list');assert false,'Unrecognised owner';
    exception when raise_exception then assert sqlerrm='Owner access is required.'; end;
  perform public.im_sl_staff(owner_id,'issue',jsonb_build_object('pass',p,'ref',tx,'note','Please recheck the reference.'));
  assert public.im_sl_student('status',hash_a,email_a)->>'status'='needs_reference';
  receipt:='QB'||substr(tx,3);
  a:=public.im_sl_student('payment',hash_a,email_a,jsonb_build_object('pass',p,'ref',receipt,'payer','Synthetic A'));
  begin perform public.im_sl_staff(owner_id,'approve',jsonb_build_object('pass',p,'ref',tx));assert false,'Stale bank reference';
    exception when raise_exception then assert sqlerrm like 'Payment details changed%'; end;
  perform public.im_sl_staff(owner_id,'approve',jsonb_build_object('pass',p,'ref',receipt));
  a:=public.im_sl_student('status',hash_a,email_a);stamp:=a->>'startsAt';
  assert a->>'status'='approved' and (a->>'endsAt')::timestamptz-stamp::timestamptz=interval '720 hours';
  perform public.im_sl_staff(owner_id,'approve',jsonb_build_object('pass',p,'ref',receipt));
  assert public.im_sl_student('status',hash_a,email_a)->>'startsAt'=stamp;
  assert public.im_sl_student('renew',hash_a,email_a)->>'id'=p::text;
  begin perform public.im_sl_student('open',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));assert false,'Unselected read';
    exception when raise_exception then assert sqlerrm like 'Choose this chapter%'; end;
  begin perform public.im_sl_student('open',hash_b,email_b,jsonb_build_object('pass',p,'chapter',ids[1]));assert false,'Other pass accepted';
    exception when raise_exception then assert sqlerrm like 'Refresh your pass%'; end;
  for k in 1..10 loop
    a:=public.im_sl_student('pick',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[k]));
    assert jsonb_array_length(a->'chapters')=k;
  end loop;
  a:=public.im_sl_student('pick',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));
  assert jsonb_array_length(a->'chapters')=10;
  begin perform public.im_sl_student('pick',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[11]));assert false,'Eleventh choice accepted';
    exception when raise_exception then assert sqlerrm like 'All 10 chapters%'; end;
  lesson:=public.im_sl_student('open',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));
  assert length(lesson->'challenge'->>'solution')>24 and length(lesson->'lessons'->0->'body'->>'steps')>10;
  u:=lesson->'lessons'->0->>'id';
  perform public.im_sl_student('complete',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1],'unit',u));
  perform public.im_sl_student('complete',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1],'unit',u));
  lesson:=public.im_sl_student('open',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));
  assert (lesson->'lessons'->0->>'complete')::boolean;
  begin perform public.im_sl_student('complete',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1],'unit','nonexistent'));assert false,'Wrong lesson accepted';
    exception when raise_exception then assert sqlerrm like 'Choose a lesson%'; end;
  update public.im_sl_passes set starts_at=now()-interval '720 hours',ends_at=now() where id=p;
  assert public.im_sl_student('status',hash_a,email_a)->>'status'='expired';
  begin perform public.im_sl_student('open',hash_a,email_a,jsonb_build_object('pass',p,'chapter',ids[1]));assert false,'Expired read';
    exception when raise_exception then assert sqlerrm like 'An active%'; end;
  a:=public.im_sl_student('renew',hash_a,email_a);
  assert a->>'id'<>p::text and a->>'status'='awaiting_payment' and jsonb_array_length(a->'chapters')=0;
  assert public.im_sl_student('renew',hash_a,email_a)->>'id'=a->>'id';
  begin perform public.im_sl_student('payment',hash_a,email_a,jsonb_build_object('pass',p,'ref',receipt,'payer','Synthetic A'));assert false,'Stale pass accepted';
    exception when raise_exception then assert sqlerrm like 'Refresh your pass%'; end;
  select count(*) into test_count from public.im_sl_progress g join public.im_sl_learners l on l.id=g.learner_id where l.key_hash=hash_a;
  assert test_count=1;
  assert jsonb_array_length(public.im_sl_staff(owner_id,'list',jsonb_build_object('email',email_a)))=2;
  update public.im_sl_release set accepting=false where singleton;
  begin perform public.im_sl_student('register',repeat('f',64),'unused@example.invalid','{"name":"Synthetic"}');assert false,'Paused checkout accepted';
    exception when raise_exception then assert sqlerrm like 'New passes are currently paused%'; end;
end;
$check$;
rollback;
select 'Passed: privacy, payment review, 30-day expiry, ten choices, chapter contents, progress and renewal. Synthetic records rolled back.' as verification;
